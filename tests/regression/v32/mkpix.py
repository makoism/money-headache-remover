# pixel art for M.H.R.2000: cute flat sprites as crisp SVG. Grids: '.' is transparent, letters index the palette.
import json, subprocess, sys

SPRITES = {}
def sprite(name, pal, rows):
    rows = [r for r in rows.strip('\n').split('\n')]
    w = max(len(r) for r in rows); h = len(rows)
    paths = {}
    for y, r in enumerate(rows):
        x = 0
        while x < len(r):
            ch = r[x]
            if ch == '.' or ch == ' ': x += 1; continue
            x0 = x
            while x < len(r) and r[x] == ch: x += 1
            paths.setdefault(ch, []).append(f'M{x0} {y}h{x - x0}v1h-{x - x0}z')
    body = ''.join(f'<path fill="{pal[c]}" d="{"".join(d)}"/>' for c, d in paths.items())
    SPRITES[name] = f'<svg viewBox="0 0 {w} {h}" shape-rendering="crispEdges" aria-hidden="true">{body}</svg>'

