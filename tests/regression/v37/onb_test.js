const L = require('/tmp/v22/lib.js'); const { w } = L;
let pass = 0, fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); c ? pass++ : fail++; };
const VW = +process.env.VW || 390, VH = +process.env.VH || 844;
(async () => {
  const { b, p, errs } = await L.launch(VW, VH, 'dark');
  const title = () => p.$eval('.tour h2, #tourTitle', e => e.textContent).catch(() => '');
  for (let i = 0; i < 4 && !/Before the uploads/.test(await title()); i++) { await p.click('#tourNext'); await w(600); }
  ok(/Before the uploads/.test(await title()), 'the conversation comes right before the uploads: ' + await title());
  ok(await p.$$eval('#onbLog .msg.ai', e => e.length) === 2 && await p.$$eval('[data-onbk]', e => e.length) === 4, 'it opens with two messages and four choices');
  ok(/Skip to uploads/.test(await p.$eval('#tourNext', e => e.textContent)), 'the footer offers Skip to uploads');
  await p.screenshot({ path: `/tmp/v37/onb-${VW}-1.png` });
  await p.click('[data-onbk="bank"]'); await p.click('[data-onbk="wallet"]'); await p.click('[data-onbk="cash"]'); await w(200);
  ok(await p.$$eval('.onb-k.on', e => e.length) === 3, 'choices toggle on');
  await p.click('#onbGo'); await w(400);
  ok(await p.$$eval('.onb-cnt', e => e.length) === 2, 'it asks how many of the two account kinds');
  await p.click('[data-onbn="bank"][data-v="2"]'); await w(150); await p.click('#onbGo'); await w(400);
  const inputs = await p.$$('[data-onbname]'); ok(inputs.length === 3, 'three name boxes: 2 banks and 1 wallet');
  await inputs[0].type('BPI'); await inputs[1].type('Metrobank'); await inputs[2].type('GCash');
  await p.click('#onbGo'); await w(500);
  const log = await p.$eval('#onbLog', e => e.textContent);
  ok(/upload boxes: BPI, Metrobank, GCash/.test(log), 'it lists the boxes by the names given');
  ok(/Cash does not show/.test(log) && /Why statements/.test(log) && /What happens/.test(log) && /How it is sorted/.test(log), 'it explains cash, why, what happens and the categories');
  ok(/Go to the uploads/.test(await p.$eval('#tourNext', e => e.textContent)), 'the footer now says Go to the uploads');
  await p.screenshot({ path: `/tmp/v37/onb-${VW}-2.png`, fullPage: false });
  await p.click('[data-onbq="extra"]'); await w(300);
  ok(/Add a line/.test(await p.$eval('#onbLog', e => e.lastElementChild.textContent)), 'a tapped question is answered at once');
  await p.type('#onbIn', 'what if my rent is paid in cash?'); await p.keyboard.press('Enter');
  await p.waitForFunction(() => /check screen/.test((document.querySelector('#onbLog').lastElementChild || {}).textContent || ''), { timeout: 15000 }).catch(() => {});
  const lastAi = await p.$eval('#onbLog', e => e.lastElementChild.textContent);
  ok(/check screen/.test(lastAi), 'a typed question without Claude gets the matching built-in answer: ' + lastAi.slice(0, 60));
  ok(/Before the uploads/.test(await title()), 'Enter in the question box does not leave the screen');
  await p.waitForFunction(() => /rent is paid in cash/.test(localStorage.getItem('money-map-template-v2') || '') && /"tourAt"/.test(localStorage.getItem('money-map-template-v2') || ''), { timeout: 8000 }).catch(() => console.log('NOTE: not saved before reload'));
  console.log('saved tourAt', await p.evaluate(() => (JSON.parse(localStorage.getItem('money-map-template-v2')).ui || {}).tourAt));
  await p.evaluate(() => sessionStorage.setItem('__keep', '1')); await p.reload(); await w(1500);
  ok(/Before the uploads/.test(await title()) && /rent is paid in cash/.test(await p.$eval('#onbLog', e => e.textContent)), 'a reload comes back to the same conversation');
  await p.click('#tourNext'); await w(700);
  ok(/Your statements/.test(await title()), 'Go to the uploads opens Your statements');
  const boxes = await p.$$eval('[data-acctname]', e => e.map(i => i.value)); const kinds = await p.$$eval('#acctList input[type=radio]:checked', e => e.map(i => i.value));
  ok(JSON.stringify(boxes) === '["BPI","Metrobank","GCash"]' && JSON.stringify(kinds) === '["bank","bank","wallet"]', 'the upload boxes are set up from the answers: ' + boxes + ' / ' + kinds);
  ok(!!await p.$('#srcChat'), 'the uploads screen links back to the questions');
  await p.click('#srcChat'); await w(600); ok(/Before the uploads/.test(await title()), 'and the link goes back');
  await p.click('#onbReset'); await w(300);
  await p.click('#onbGo'); await w(400);
  ok(/no statements to upload/.test(await p.$eval('#onbLog', e => e.textContent)), 'None of these says to type the numbers instead');
  ok(errs.length === 0, 'no page errors ' + errs.join(' | '));
  console.log(`ONB: ${pass} pass, ${fail} fail`); await b.close(); process.exit(fail ? 1 : 0);
})();
